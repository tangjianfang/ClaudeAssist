export type AiModelCategory = 'frontier' | 'coding' | 'reasoning' | 'multimodal' | 'open';
export type CostTier = 'low' | 'medium' | 'high';

export interface AiScores {
  reasoning: number;
  coding: number;
  toolUse: number;
  consistency: number;
  latency: number;
}

export interface AiModel {
  id: string;
  name: string;
  vendor: string;
  category: AiModelCategory;
  version: string;
  contextWindow: string;
  costTier: CostTier;
  pricing: {
    currency: 'USD' | 'CNY';
    inputPerMTokens: string;
    outputPerMTokens: string;
    notes: string;
    officialUrl: string;
  };
  scores: AiScores;
  china: {
    accessible: boolean;
    needsProxy: boolean;
    localDeploy: boolean;
    complianceRisk: 'low' | 'medium' | 'high';
    note: string;
  };
  tags: string[];
  pros: string[];
  cons: string[];
  changeLog: string[];
  source: {
    label: string;
    url: string;
    checkedAt: string;
  };
}

export interface AiRecommendation {
  scene: string;
  model: string;
  agent: string;
  toolchain: string;
  pros: string[];
  cons: string[];
  risk: string;
}

export type AiToolCategory = 'ide' | 'editor' | 'platform' | 'specialized' | 'workflow';
export type AiToolFeature = 'code-completion' | 'code-generation' | 'code-execution' | 'refactoring' | 'testing' | 'documentation' | 'debugging' | 'optimization' | 'api-integration' | 'voice-control' | 'terminal' | 'agents' | 'multi-file' | 'chat' | 'file-editing' | 'security-scanning' | 'local-private' | 'git-integration' | 'web-search' | 'image-analysis';

export interface AiTool {
  id: string;
  name: string;
  vendor: string;
  category: AiToolCategory;
  version: string;
  compatible: string[]; // 兼容的 IDE/编辑器，如 'VSCode', 'JetBrains', 'Neovim' 等
  costTier: CostTier;
  pricing: {
    currency: 'USD' | 'CNY';
    plan: string; // e.g., "Free", "$10/month", "Enterprise"
    notes: string;
    officialUrl: string;
  };
  features: AiToolFeature[];
  scores: {
    codeCompletion: number;
    codeGeneration: number;
    efficiency: number;
    accuracy: number;
    contextAwareness: number;
  };
  china: {
    accessible: boolean;
    needsProxy: boolean;
    alternativeAvailable: boolean;
    note: string;
  };
  supportedModels: string[]; // 支持的模型，如 GPT-4, Claude 等
  tags: string[];
  pros: string[];
  cons: string[];
  source: {
    label: string;
    url: string;
    checkedAt: string;
  };
}

export interface AiToolCombination {
  id: string;
  name: string;
  scenario: string;
  model: string;
  tool: string;
  complementaryTools?: string[]; // 推荐的辅助工具
  totalMonthlyCost: string;
  developmentSpeed: string; // 'fast', 'medium', 'slow'
  learningCurve: string; // 'easy', 'medium', 'hard'
  supportLevel: string; // 'enterprise', 'community', 'limited'
  pros: string[];
  cons: string[];
  bestFor: string[];
  riskFactors: string[];
  setupTime: string; // e.g., "5 minutes", "1 hour"
}

