// Helper to get tool by ID
export function getToolById(id: string): AiTool | undefined {
  return DATA_STORE.tools.find(tool => tool.id === id);
}

// Helper to filter tools by category
export function getToolsByCategory(category: AiToolCategory): AiTool[] {
  return DATA_STORE.tools.filter(tool => tool.category === category);
}

// Helper to get combinations for a specific model
export function getCombinationsForModel(modelId: string): AiToolCombination[] {
  const model = DATA_STORE.models.find(m => m.id === modelId);
  if (!model) return [];
  
  return DATA_STORE.toolCombinations.filter(combo => 
    combo.model === model.name || combo.model.includes(model.name)
  );
}

// Helper to get combinations for a specific tool
export function getCombinationsForTool(toolId: string): AiToolCombination[] {
  const tool = getToolById(toolId);
  if (!tool) return [];
  
  return DATA_STORE.toolCombinations.filter(combo => 
    combo.tool === tool.name
  );
}
